"""
utils/exporters.py
==================
Canonical Document Exporters for ResearchAI:
- Markdown (.md)
- Microsoft Word (.docx via `python-docx`) with Academic Title Block, Metadata,
  Headings, Tables, Embedded Figures, and Canonical Reference List
- Publication-Ready PDF (.pdf via `reportlab` with `fpdf2` fallback)
"""

from __future__ import annotations

import io
import re
from datetime import datetime
from typing import Any, Dict, List, Optional

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor

from utils.reference_library import format_citation


def _strip_markdown_inline(text: str) -> str:
    """Clean markdown inline syntax for clean PDF/DOCX plain rendering."""
    s = re.sub(r"\*\*(.*?)\*\*", r"\1", text)
    s = re.sub(r"\*(.*?)\*", r"\1", s)
    s = re.sub(r"`(.*?)`", r"\1", s)
    return s.strip()


def export_to_markdown(
    title: str,
    content_md: str,
    references: Optional[List[Dict[str, Any]]] = None,
    citation_style: str = "APA",
    metadata: Optional[Dict[str, str]] = None,
) -> bytes:
    """Build a complete, canonical Markdown manuscript including verified references."""
    meta = metadata or {}
    lines = [
        f"# {title}",
        "",
        f"**Generated by**: ResearchAI — *Five AI Agents. One Smarter Research Journey.*",
        f"**Date**: {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}",
    ]
    if meta.get("field"):
        lines.append(f"**Research Field**: {meta['field']}")
    if meta.get("career_stage"):
        lines.append(f"**Researcher Stage**: {meta['career_stage']}")
    if meta.get("target_journal"):
        lines.append(f"**Target Venue**: {meta['target_journal']}")
    lines.append(f"**Citation Style**: {citation_style}")
    lines.extend(
        [
            "",
            "> **Academic Responsibility & Verification Notice**: All outputs must be verified by the researcher and approved by their supervisor. The researcher is solely responsible for originality, empirical accuracy, ethics, and journal policy compliance.",
            "",
            "---",
            "",
            content_md.strip(),
            "",
        ]
    )

    # Append canonical Verified Reference Library if not already embedded or as a master appendix
    if references:
        lines.extend(
            [
                "",
                "---",
                "",
                f"## Verified Reference Library ({citation_style} Format)",
                "",
            ]
        )
        for idx, ref in enumerate(references, start=1):
            lines.append(f"{idx}. {format_citation(ref, index=idx, style=citation_style)}")

    lines.extend(
        [
            "",
            "---",
            "*ResearchAI — Higher Research, Brighter Tomorrow.*",
        ]
    )
    return "\n".join(lines).encode("utf-8")


def export_to_docx(
    title: str,
    content_md: str,
    references: Optional[List[Dict[str, Any]]] = None,
    citation_style: str = "APA",
    metadata: Optional[Dict[str, str]] = None,
    figures: Optional[List[Dict[str, Any]]] = None,
) -> bytes:
    """
    Convert Markdown manuscript + verified references + optional experiment figures
    into a canonically formatted Microsoft Word (.docx) document.
    """
    doc = Document()

    # Configure base Normal style (Times New Roman / 11pt academic layout)
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(11)

    # Title block
    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run_t = title_p.add_run(title)
    run_t.bold = True
    run_t.font.size = Pt(16)
    run_t.font.color.rgb = RGBColor(15, 23, 42)

    meta = metadata or {}
    sub_p = doc.add_paragraph()
    sub_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    meta_parts = [
        f"Field: {meta.get('field', 'General Research')}",
        f"Citation Style: {citation_style}",
        f"Date: {datetime.utcnow().strftime('%Y-%m-%d')}",
    ]
    if meta.get("target_journal"):
        meta_parts.append(f"Target Journal: {meta['target_journal']}")
    sub_run = sub_p.add_run(" | ".join(meta_parts))
    sub_run.italic = True
    sub_run.font.size = Pt(9.5)
    sub_run.font.color.rgb = RGBColor(71, 85, 105)

    disc_p = doc.add_paragraph()
    disc_run = disc_p.add_run(
        "Verification Disclaimer: All claims, statistics, and citations in this manuscript must be verified by the author(s) and approved by their academic supervisor prior to submission."
    )
    disc_run.italic = True
    disc_run.font.size = Pt(8.5)
    disc_run.font.color.rgb = RGBColor(100, 116, 139)

    # Parse markdown lines into Word headings, bullets, tables, and paragraphs
    lines = content_md.splitlines()
    table_buffer: List[List[str]] = []

    def _flush_table_buffer() -> None:
        nonlocal table_buffer
        if not table_buffer:
            return
        # Remove markdown separator row like |---|---|
        rows = [
            r for r in table_buffer
            if not all(re.match(r"^:?-{2,}:?$", cell.strip()) for cell in r if cell.strip())
        ]
        if rows:
            max_cols = max(len(r) for r in rows)
            tbl = doc.add_table(rows=len(rows), cols=max_cols)
            tbl.style = "Table Grid"
            for r_idx, row_vals in enumerate(rows):
                for c_idx in range(max_cols):
                    val = row_vals[c_idx] if c_idx < len(row_vals) else ""
                    cell = tbl.cell(r_idx, c_idx)
                    cell.text = _strip_markdown_inline(val)
                    if r_idx == 0:
                        for p in cell.paragraphs:
                            for run in p.runs:
                                run.bold = True
        table_buffer = []

    for raw_line in lines:
        line = raw_line.rstrip()

        # Markdown table detection
        if line.strip().startswith("|") and line.strip().endswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            table_buffer.append(cells)
            continue
        else:
            _flush_table_buffer()

        if not line.strip():
            continue

        if line.startswith("# "):
            doc.add_heading(_strip_markdown_inline(line[2:]), level=1)
        elif line.startswith("## "):
            doc.add_heading(_strip_markdown_inline(line[3:]), level=2)
        elif line.startswith("### "):
            doc.add_heading(_strip_markdown_inline(line[4:]), level=3)
        elif line.startswith("#### "):
            doc.add_heading(_strip_markdown_inline(line[5:]), level=4)
        elif line.lstrip().startswith(("- ", "* ")):
            bullet_text = _strip_markdown_inline(line.lstrip()[2:])
            doc.add_paragraph(bullet_text, style="List Bullet")
        elif re.match(r"^\d+\.\s+", line.lstrip()):
            num_text = _strip_markdown_inline(re.sub(r"^\d+\.\s+", "", line.lstrip()))
            doc.add_paragraph(num_text, style="List Number")
        elif line.strip() == "---":
            continue
        else:
            p = doc.add_paragraph(_strip_markdown_inline(line))
            p.paragraph_format.space_after = Pt(6)

    _flush_table_buffer()

    # Embed figures if provided
    if figures:
        doc.add_heading("Figures & Empirical Visualizations", level=1)
        for fig in figures:
            img_bytes = fig.get("bytes")
            if img_bytes:
                try:
                    doc.add_picture(io.BytesIO(img_bytes), width=Inches(5.5))
                    cap = doc.add_paragraph(f"Figure: {fig.get('name', 'Analysis Figure')}")
                    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
                except Exception:
                    pass

    # Append Verified Reference Library
    if references:
        doc.add_heading(f"Verified Reference Library ({citation_style})", level=1)
        for idx, ref in enumerate(references, start=1):
            p = doc.add_paragraph(_strip_markdown_inline(f"[{idx}] " if citation_style.upper() == "IEEE" else f"{idx}. ") + _strip_markdown_inline(format_citation(ref, index=idx, style=citation_style)))
            p.paragraph_format.space_after = Pt(4)

    footer_p = doc.add_paragraph()
    footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    f_run = footer_p.add_run("ResearchAI — Higher Research, Brighter Tomorrow.")
    f_run.italic = True
    f_run.font.size = Pt(9)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def export_to_pdf(
    title: str,
    content_md: str,
    references: Optional[List[Dict[str, Any]]] = None,
    citation_style: str = "APA",
    metadata: Optional[Dict[str, str]] = None,
) -> bytes:
    """
    Generate a clean, multi-page academic PDF using ReportLab Platypus (with fpdf2 fallback).
    """
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import inch
        from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer
        from xml.sax.saxutils import escape

        buf = io.BytesIO()
        doc = SimpleDocTemplate(
            buf,
            pagesize=A4,
            leftMargin=0.85 * inch,
            rightMargin=0.85 * inch,
            topMargin=0.85 * inch,
            bottomMargin=0.85 * inch,
            title=title,
            author="ResearchAI Multi-Agent System",
        )
        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Title"],
            fontSize=16,
            leading=20,
            textColor=colors.HexColor("#0f172a"),
            spaceAfter=8,
        )
        meta_style = ParagraphStyle(
            "DocMeta",
            parent=styles["Normal"],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#475569"),
            spaceAfter=6,
        )
        h1_style = ParagraphStyle(
            "DocH1",
            parent=styles["Heading1"],
            fontSize=13,
            leading=16,
            textColor=colors.HexColor("#0f172a"),
            spaceBefore=12,
            spaceAfter=6,
        )
        h2_style = ParagraphStyle(
            "DocH2",
            parent=styles["Heading2"],
            fontSize=11.5,
            leading=14,
            textColor=colors.HexColor("#1e293b"),
            spaceBefore=10,
            spaceAfter=4,
        )
        body_style = ParagraphStyle(
            "DocBody",
            parent=styles["BodyText"],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#1e293b"),
            spaceAfter=5,
        )
        bullet_style = ParagraphStyle(
            "DocBullet",
            parent=body_style,
            leftIndent=14,
            spaceAfter=3,
        )

        story = []
        story.append(Paragraph(escape(title), title_style))

        meta = metadata or {}
        meta_line = (
            f"<b>Field:</b> {escape(meta.get('field', 'Academic Research'))} &nbsp;|&nbsp; "
            f"<b>Citation Style:</b> {escape(citation_style)} &nbsp;|&nbsp; "
            f"<b>Date:</b> {datetime.utcnow().strftime('%Y-%m-%d')}"
        )
        story.append(Paragraph(meta_line, meta_style))
        story.append(
            Paragraph(
                "<i>Disclaimer: All outputs, citations, and statistical findings must be verified by the researcher and approved by their academic supervisor.</i>",
                meta_style,
            )
        )
        story.append(HRFlowable(width="100%", thickness=0.7, color=colors.HexColor("#cbd5e1"), spaceAfter=10))

        for raw_line in content_md.splitlines():
            line = raw_line.strip()
            if not line or line == "---":
                story.append(Spacer(1, 4))
                continue
            clean = escape(_strip_markdown_inline(line))
            if line.startswith("# "):
                story.append(Paragraph(escape(_strip_markdown_inline(line[2:])), h1_style))
            elif line.startswith("## "):
                story.append(Paragraph(escape(_strip_markdown_inline(line[3:])), h2_style))
            elif line.startswith("### ") or line.startswith("#### "):
                story.append(Paragraph(f"<b>{escape(_strip_markdown_inline(line.lstrip('#').strip()))}</b>", body_style))
            elif line.startswith(("- ", "* ")):
                story.append(Paragraph(f"&bull; {escape(_strip_markdown_inline(line[2:]))}", bullet_style))
            else:
                story.append(Paragraph(clean, body_style))

        if references:
            story.append(Spacer(1, 10))
            story.append(HRFlowable(width="100%", thickness=0.7, color=colors.HexColor("#cbd5e1"), spaceAfter=8))
            story.append(Paragraph(escape(f"Verified Reference Library ({citation_style})"), h1_style))
            for idx, ref in enumerate(references, start=1):
                cite_txt = escape(_strip_markdown_inline(format_citation(ref, index=idx, style=citation_style)))
                story.append(Paragraph(f"{idx}. {cite_txt}", bullet_style))

        story.append(Spacer(1, 14))
        story.append(Paragraph("<i>ResearchAI — Higher Research, Brighter Tomorrow.</i>", meta_style))

        doc.build(story)
        return buf.getvalue()

    except Exception:
        # Fallback to fpdf2 if ReportLab encounters any font/encoding issue
        from fpdf import FPDF

        pdf = FPDF()
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()
        pdf.set_font("Helvetica", "B", 15)
        safe_title = title.encode("latin-1", "replace").decode("latin-1")
        pdf.multi_cell(0, 9, safe_title)
        pdf.ln(3)
        pdf.set_font("Helvetica", "", 10)
        for line in content_md.splitlines():
            safe_line = _strip_markdown_inline(line).encode("latin-1", "replace").decode("latin-1")
            pdf.multi_cell(0, 6, safe_line)
        return bytes(pdf.output())
